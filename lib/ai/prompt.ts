import type { PregInfo, Role } from "@/lib/preg";
import { fa } from "@/lib/jalali";

function situation(info: PregInfo) {
  if (!info.born) return `بارداری الان ${info.week} هفته و ${info.day} روزه است (سه‌ماهه‌ی ${info.week < 14 ? "اول" : info.week < 28 ? "دوم" : "سوم"}).`;
  const d = info.ageDays;
  if (d < 60) return `نوزاد به دنیا اومده و حدود ${Math.floor(d / 7)} هفته (${d} روز) سن داره.`;
  return `نوزاد به دنیا اومده و حدود ${Math.floor(d / 30.4)} ماه سن داره.`;
}


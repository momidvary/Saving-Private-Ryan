// تشخیص علائم خطر در متن سؤال. این بررسی قبل از هوش مصنوعی انجام می‌شه تا پیام اورژانس هیچ‌وقت منتظر جواب مدل نمونه.
// فهرست عمداً گسترده‌ست؛ هشدار اضافه بهتر از هشدار جاافتاده‌ست.

const PATTERNS: RegExp[] = [
  /(^|[^آ-ی])تب(?![ریل])/, // تب، تب کرده، تبخال؛ ولی نه «تبریک» یا «مرتب»
  /درجه/,
  /تشنج/,
  /خون ?‌?ریزی|لکه ?‌?بینی|خون (اومد|میاد|آمد)/,
  /نفس (نمی|نمی‌|سخت|تند|بند)|تنگی نفس|خس ?‌?خس/,
  /کبود/,
  /بی ?‌?هوش|بی ?‌?حال|بیدار نمی/,
  /حرک(ت|ات)(ش)? (نمی|کم|نداره|ندار)|تکون (نمی|نخورده|کم)/,
  /آب ?‌?ریزش|کیسه ?‌?(ی )?آب/,
  /سردرد شدید|تاری دید|ورم (ناگهانی|صورت)/,
  /درد شدید|درد قفسه/,
  /زردی/,
  /استفراغ (سبز|جهنده|مداوم|شدید)/,
  /شیر نمی ?‌?خوره|شیر نخورده/,
  /خودکشی|آسیب (به )?(خودم|بچه)|بکشم/,
  /مسموم|سوختگی|زمین خورد|از (تخت|بلندی) افتاد/,
];

export function hasRedFlag(text: string) {
  return PATTERNS.some((p) => p.test(text));
}

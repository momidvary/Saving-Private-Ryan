/** درجه‌ها بر اساس تعداد مدال‌ها */
export const RANKS: { min: number; name: string }[] = [
  { min: 0, name: "سرباز تازه‌نفس" },
  { min: 3, name: "سرباز" },
  { min: 6, name: "سرجوخه" },
  { min: 10, name: "گروهبان" },
  { min: 15, name: "ستوان" },
  { min: 21, name: "سروان" },
  { min: 28, name: "سرگرد" },
  { min: 36, name: "سرهنگ" },
  { min: 45, name: "ژنرال" },
];

export function rankFor(medals: number) {
  let i = 0;
  for (let k = 0; k < RANKS.length; k++) if (medals >= RANKS[k].min) i = k;
  return { rank: RANKS[i], next: RANKS[i + 1] ?? null };
}

/** مرحله‌ی فعلی بر اساس سن (روز نسبت به تولد) */
export function currentStageIndex(ageDays: number) {
  const i = STAGES.findIndex((s) => ageDays >= s.from && ageDays < s.to);
  return i < 0 ? STAGES.length - 1 : i;
}

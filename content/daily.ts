export function babyLine(week: number) {
  if (week < 14) return "رایان داره سریع رشد می‌کنه؛ اندام‌های اصلیش شکل گرفتن.";
  if (week < 18) return "کم‌کم حرکات رایان برای مامان قابل حس می‌شه.";
  if (week < 20) return "شنوایی رایان داره شکل می‌گیره.";
  if (week < 24) return "رایان کم‌کم صداها رو می‌شنوه؛ صدای شما هم جزوشونه.";
  if (week < 28) return "ریه‌ها و مغز رایان با سرعت در حال رشدن و حرکاتش قوی‌تر شده.";
  if (week < 32) return "رایان چشم‌هاش رو باز و بسته می‌کنه و وزنش سریع بالا می‌ره.";
  if (week < 37) return "بیشترِ کارِ این هفته‌ها وزن‌گیریه؛ ریه‌ها هنوز در حال کامل شدنن.";
  return "رایان برای تولد آماده می‌شه. هر روز این هفته‌ها برای مغزش ارزشمنده.";
}

import type { Role, Stage } from "@/lib/preg";

export type Task = { id: string; text: string };

// کارهای روزانه. هر کار یه شناسه‌ی ثابت داره که تیک‌ها با اون ذخیره می‌شن؛ شناسه‌ها رو عوض نکنید.
export function dailyTasks(role: Role, stage: Stage): Task[] {
  const t3 = stage === "t3" || stage === "late";
  if (role === "mom") {
    if (stage === "post")
      return [
        { id: "pm-rest", text: "هر وقت رایان خوابید، من هم استراحت کردم" },
        { id: "pm-food", text: "آب و غذای کافی خوردم" },
        { id: "pm-supp", text: "مکمل‌هام رو طبق دستور خوردم" },
        { id: "pm-share", text: "حالم رو با همسرم در میون گذاشتم" },
        { id: "pm-skin", text: "چند دقیقه پوست با پوست یا بغل آروم با رایان" },
      ];
    const list: Task[] = [
      { id: "m-supp", text: "مکمل‌های امروز رو طبق دستور پزشک خوردم" },
      { id: "m-water", text: "حدود ۸ لیوان آب خوردم" },
      { id: "m-food", text: "یه وعده‌ی کامل با سبزی و پروتئین، و یه میان‌وعده‌ی سالم" },
      { id: "m-move", text: "۲۰ تا ۳۰ دقیقه پیاده‌روی سبک (اگه پزشک منعی نکرده)" },
      { id: "m-rest", text: t3 ? "یه استراحت کوتاه وسط روز، به پهلو" : "یه استراحت کوتاه وسط روز" },
    ];
    if (t3) list.push({ id: "m-kicks", text: "حرکات رایان رو حس کردم و مثل همیشه بود" });
    list.push({ id: "m-mind", text: "۵ دقیقه برای خودم: نفس عمیق، موسیقی یا هر چیزی که آرومم می‌کنه" });
    return list;
  }
  if (stage === "post")
    return [
      { id: "pd-night", text: "یه نوبت شب، پوشک یا آروغ گرفتن با من بود" },
      { id: "pd-feed", text: "آب و غذای مادر رو کنارش گذاشتم" },
      { id: "pd-guests", text: "مهمون‌ها و تلفن‌ها رو مدیریت کردم تا مادر استراحت کنه" },
      { id: "pd-skin", text: "چند دقیقه پوست با پوست یا بغل آروم با رایان" },
      { id: "pd-ask", text: "پرسیدم حالش چطوره و فقط گوش دادم" },
    ];
  const list: Task[] = [
    { id: "d-chore", text: "یه کار خونه رو کامل از دوشش برداشتم" },
    { id: "d-snack", text: "میوه یا میان‌وعده‌ی سالم براش آماده کردم" },
    { id: "d-ask", text: "پرسیدم امروز حالش چطوره و فقط گوش دادم" },
    { id: "d-talk", text: "چند دقیقه با رایان حرف زدم یا براش خوندم" },
    { id: "d-walk", text: "با هم پیاده‌روی کردیم" },
  ];
  if (stage === "late") list.push({ id: "d-ready", text: "گوشیم شارژه و در دسترسم" });
  return list;
}

